# ---- 表示モード ------------------------------------------------------------
# 'abs' = 素の騰落率。'rel' = その日の市場（全セクター等加重平均）を差し引いた残差。
#
# ⚠️ **rel こそがこの画面の主目的に答えるモード**。abs は「市場が上げたか」と
# 「どのテーマに資金が入ったか」が混ざる。市場が+2%の日は全行が緑になり何も読めない。
# 実測（US・n=617日）: 生の相関は全ペアが正(+0.05〜+0.58)で市場ファクターに埋もれるが、
# 市場を引くと ビッグテック/金融/医療系/金銀(+0.33〜+0.48) ⇔ 量子系/暗号資産(-0.40〜-0.54)
# という**リスクオン・オフの綱引き**が現れる。absだけ見ていると、高ベータ行が濃く
# 低ベータ行が薄いだけの状態を「逆相関」と誤読する（実際に誤読が起きた）。
IMPULSE_MODES = (('abs', '絶対'), ('rel', '対市場'))
DEFAULT_MODE = 'abs'


def impulse_universe(country):
    """その国の全対象コードのリスト（重複除去・定義順維持）。ダミー行は空なので寄与しない"""
    seen = []
    for sec in IMPULSE_SECTORS.get(country, []):
        for c in sec.get('codes') or []:
            if c not in seen:
                seen.append(c)
    return seen


def dummy_change(sector_name, day):
    """ダミー行のセル値（%）。セクター名と日付から決まる決定的な擬似乱数

    ランダムだと再読み込みのたびに色が変わって「実データではない」ことが
    伝わりにくいので、同じ日・同じセクターなら常に同じ値になるようにする。
    分布は概ね -2.5%〜+2.5%。
    """
    import hashlib

    h = hashlib.md5(f'{sector_name}:{day.isoformat()}'.encode()).digest()
    raw = int.from_bytes(h[:4], 'big') / 0xFFFFFFFF   # 0.0〜1.0
    return round((raw - 0.5) * 5.0, 2)
