# ---- モメンタムの段階分け（7段階） -----------------------------------------
# |z| をこの境界で区切り、中立1＋上下各3段の**7段階**に分類する。
# 3値だと「継続中の弱い上昇」と「転換の号砲になる大陽線」が同じ色に潰れ、
# トレンドの**強さの変化**が読めない。段階を増やす目的はそこにある。
#
# ⚠️ 境界値を安易に動かさないこと。正規分布近似での20営業日あたりの出現数は
#   中立 7.7日 / 弱 7.7日 / 強 3.7日 / 極 0.9日 で、**極が「月に1回」**に収まる。
#   外側を 2.5σ にすると極の出現率が0.6%になり、ほぼ空のバケットになる。
#   逆に 1.5σ にすると「強」と混ざって段階を増やした意味が消える。
#   なお SIGMA_STEPS[0]（中立幅）は「20日中6〜11日が中立」になるよう調整済みの
#   実測値なので、ここは特に動かさない。
SIGMA_STEPS = (0.5, 1.2, 2.0)   # 中立|弱 / 弱|強 / 強|極 の境界（σ倍）

